"""Built-in, dependency-independent project template definitions."""

from dataclasses import dataclass
from textwrap import dedent


@dataclass(frozen=True, slots=True)
class TemplateSpec:
    """Metadata shown by the CLI and used during rendering."""

    name: str
    summary: str
    run_command: str


TEMPLATE_SPECS = (
    TemplateSpec(
        name="fastapi",
        summary="Small HTTP API with a health endpoint and Uvicorn runner.",
        run_command="PROJECT_NAME",
    ),
    TemplateSpec(
        name="flask",
        summary="Small Flask service with a health endpoint.",
        run_command="PROJECT_NAME",
    ),
    TemplateSpec(
        name="streamlit",
        summary="Interactive Streamlit application with one testable core function.",
        run_command="python -m streamlit run src/MODULE_NAME/main.py",
    ),
    TemplateSpec(
        name="discord",
        summary="Discord bot with explicit token validation and minimal intents.",
        run_command="PROJECT_NAME",
    ),
)

TEMPLATE_BY_NAME = {spec.name: spec for spec in TEMPLATE_SPECS}
TEMPLATE_NAMES = tuple(TEMPLATE_BY_NAME)
DEFAULT_TEMPLATE = "fastapi"


def _pyproject(
    *,
    project_name: str,
    module_name: str,
    dependencies: tuple[str, ...],
    script_target: str | None,
) -> str:
    lines = [
        "[build-system]",
        'requires = ["setuptools>=83,<84", "wheel>=0.45,<1"]',
        'build-backend = "setuptools.build_meta"',
        "",
        "[project]",
        f'name = "{project_name}"',
        'version = "0.1.0"',
        f'description = "A {project_name} project generated by Samsarix CLI"',
        'readme = "README.md"',
        'requires-python = ">=3.11"',
        "dependencies = [",
        *(f'    "{dependency}",' for dependency in dependencies),
        "]",
    ]
    if script_target is not None:
        command_name = project_name.lower().replace("_", "-")
        lines.extend(
            (
                "",
                "[project.scripts]",
                f'{command_name} = "{module_name}.main:{script_target}"',
            )
        )

    lines.extend(
        (
            "",
            "[project.optional-dependencies]",
            "dev = [",
            '    "pytest>=8,<10",',
            '    "ruff>=0.11,<1",',
            "]",
            "",
            "[tool.setuptools.packages.find]",
            'where = ["src"]',
            "namespaces = false",
            "",
            "[tool.pytest.ini_options]",
            'testpaths = ["tests"]',
            "",
            "[tool.ruff]",
            "line-length = 100",
            'target-version = "py311"',
        )
    )
    return "\n".join(lines) + "\n"


def _readme(
    *,
    project_name: str,
    module_name: str,
    template_name: str,
    run_command: str,
    configuration: str,
) -> str:
    return (
        dedent(
            f"""
            # {project_name}

            A standalone Python project generated with the Samsarix CLI `{template_name}` template.
            It has no runtime dependency on Samsarix CLI or on a hosted service.

            ## Requirements

            - Python 3.11 or newer

            ## Setup

            ```bash
            python -m venv .venv
            ```

            Activate the environment:

            ```powershell
            # Windows PowerShell
            .venv\\Scripts\\Activate.ps1
            ```

            ```bash
            # macOS or Linux
            source .venv/bin/activate
            ```

            Install the application and development tools:

            ```bash
            python -m pip install --upgrade pip "setuptools>=83,<84"
            python -m pip install -e ".[dev]"
            ```

            ## Run

            ```bash
            {run_command}
            ```

            {configuration}

            ## Verify

            ```bash
            pytest
            ruff check .
            ruff format --check .
            ```

            If Samsarix CLI is installed, its structural check is also available:

            ```bash
            samsarix check .
            ```

            ## Layout

            - `src/{module_name}/`: application source
            - `tests/`: focused tests
            - `.samsarix/project.json`: generator metadata used by `samsarix check`

            ## License

            No license is selected for generated projects. Choose and add a license before
            redistributing this project.
            """
        ).strip()
        + "\n"
    )


def _common_files(project_name: str, module_name: str) -> dict[str, str]:
    return {
        ".gitignore": dedent(
            """
            __pycache__/
            *.py[cod]
            .coverage
            .env
            .pytest_cache/
            .ruff_cache/
            .venv/
            build/
            dist/
            *.egg-info/
            """
        ).lstrip(),
        f"src/{module_name}/__init__.py": (
            f'"""{project_name} application package."""\n\n__version__ = "0.1.0"\n'
        ),
    }


def _fastapi_files(project_name: str, module_name: str) -> dict[str, str]:
    command_name = project_name.lower().replace("_", "-")
    files = _common_files(project_name, module_name)
    files.update(
        {
            "pyproject.toml": _pyproject(
                project_name=project_name,
                module_name=module_name,
                dependencies=("fastapi>=0.100,<1", "uvicorn>=0.23,<1"),
                script_target="main",
            ),
            "README.md": _readme(
                project_name=project_name,
                module_name=module_name,
                template_name="fastapi",
                run_command=command_name,
                configuration=(
                    "The service binds to `127.0.0.1:8000` by default. Open "
                    "`http://127.0.0.1:8000/health` to verify it."
                ),
            ),
            f"src/{module_name}/main.py": dedent(
                f'''\
                """HTTP entry point for {project_name}."""

                from fastapi import FastAPI

                app = FastAPI(title="{project_name}")


                def health_payload() -> dict[str, str]:
                    """Return the stable readiness response."""
                    return {{"status": "ok"}}


                @app.get("/health")
                async def health() -> dict[str, str]:
                    """Report that the process is ready to accept requests."""
                    return health_payload()


                def main() -> None:
                    """Run the development server on the loopback interface."""
                    import uvicorn

                    uvicorn.run("{module_name}.main:app", host="127.0.0.1", port=8000)


                if __name__ == "__main__":
                    main()
                '''
            ),
            "tests/test_app.py": dedent(
                f"""\
                from {module_name}.main import health_payload


                def test_health_payload() -> None:
                    assert health_payload() == {{"status": "ok"}}
                """
            ),
        }
    )
    return files


