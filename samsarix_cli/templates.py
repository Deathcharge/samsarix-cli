def _streamlit_files(project_name: str, module_name: str) -> dict[str, str]:
    run_command = f"python -m streamlit run src/{module_name}/main.py"
    files = _common_files(project_name, module_name)
    files.update(
        {
            "pyproject.toml": _pyproject(
                project_name=project_name,
                module_name=module_name,
                dependencies=("streamlit>=1.40,<2",),
                script_target=None,
            ),
            "README.md": _readme(
                project_name=project_name,
                module_name=module_name,
                template_name="streamlit",
                run_command=run_command,
                configuration=(
                    "Streamlit prints the local application URL when it starts. The starter does "
                    "not collect credentials or call an external API."
                ),
            ),
            f"src/{module_name}/main.py": dedent(
                f'''\
                """Streamlit entry point for {project_name}."""

                import streamlit as st


                def greeting(name: str) -> str:
                    """Build the message shown by the application."""
                    cleaned_name = name.strip()
                    return f"Hello, {{cleaned_name or 'world'}}!"


                def main() -> None:
                    """Render the application."""
                    st.set_page_config(page_title="{project_name}")
                    st.title("{project_name}")
                    name = st.text_input("Your name")
                    st.write(greeting(name))


                if __name__ == "__main__":
                    main()
                '''
            ),
            "tests/test_app.py": dedent(
                f"""\
                from {module_name}.main import greeting


                def test_greeting_uses_a_safe_default() -> None:
                    assert greeting("  ") == "Hello, world!"


                def test_greeting_trims_the_name() -> None:
                    assert greeting(" Ada ") == "Hello, Ada!"
                """
            ),
        }
    )
    return files


def _discord_files(project_name: str, module_name: str) -> dict[str, str]:
    command_name = project_name.lower().replace("_", "-")
    files = _common_files(project_name, module_name)
    files.update(
        {
            "pyproject.toml": _pyproject(
                project_name=project_name,
                module_name=module_name,
                dependencies=("discord.py>=2.4,<3",),
                script_target="main",
            ),
            "README.md": _readme(
                project_name=project_name,
                module_name=module_name,
                template_name="discord",
                run_command=command_name,
                configuration=dedent(
                    """
                    Create a Discord application and bot, then expose the token only through the
                    process environment. Never commit it:

                    ```powershell
                    # Windows PowerShell
                    $env:DISCORD_TOKEN = "replace-with-your-token"
                    ```

                    ```bash
                    # macOS or Linux
                    export DISCORD_TOKEN="replace-with-your-token"
                    ```

                    The starter requests only the default gateway intents and responds to the
                    `hello` slash command. Invite and permission configuration remains an owner
                    task.
                    """
                ).strip(),
            ),
            f"src/{module_name}/main.py": dedent(
                f'''\
                """Discord entry point for {project_name}."""

                import os

                import discord


                def discord_token() -> str:
                    """Load the bot token without logging or persisting it."""
                    token = os.environ.get("DISCORD_TOKEN", "").strip()
                    if not token:
                        raise RuntimeError(
                            "DISCORD_TOKEN is required. Set it in the process environment."
                        )
                    return token


                class StarterClient(discord.Client):
                    """Minimal client that registers one slash command."""

                    def __init__(self) -> None:
                        super().__init__(intents=discord.Intents.default())
                        self.tree = discord.app_commands.CommandTree(self)

                    async def setup_hook(self) -> None:
                        await self.tree.sync()


                client = StarterClient()


                @client.tree.command(name="hello", description="Say hello")
                async def hello(interaction: discord.Interaction) -> None:
                    """Respond without exposing message-content access."""
                    await interaction.response.send_message("Hello from {project_name}!")


                def main() -> None:
                    """Run the bot until interrupted."""
                    client.run(discord_token(), log_handler=None)


                if __name__ == "__main__":
                    main()
                '''
            ),
            "tests/test_config.py": dedent(
                f"""\
                import pytest

                from {module_name}.main import discord_token


                def test_discord_token_is_required(monkeypatch: pytest.MonkeyPatch) -> None:
                    monkeypatch.delenv("DISCORD_TOKEN", raising=False)
                    with pytest.raises(RuntimeError, match="DISCORD_TOKEN is required"):
                        discord_token()


                def test_discord_token_is_trimmed(monkeypatch: pytest.MonkeyPatch) -> None:
                    monkeypatch.setenv("DISCORD_TOKEN", " test-token ")
                    assert discord_token() == "test-token"
                """
            ),
        }
    )
    return files


_RENDERERS = {
    "fastapi": _fastapi_files,
    "flask": _flask_files,
    "streamlit": _streamlit_files,
    "discord": _discord_files,
}


def render_project(project_name: str, module_name: str, template_name: str) -> dict[str, str]:
    """Render all tracked text files for one built-in starter."""
    try:
        renderer = _RENDERERS[template_name]
    except KeyError as exc:
        raise ValueError(f"Unknown template: {template_name}") from exc
    return renderer(project_name, module_name)
